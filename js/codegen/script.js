// The whole project as one R script that reproduces every table, analysis and graph.
import { topoOrder, itemCode, itemPackages } from '../model.js';
import { ABOUT, CITATION } from '../about.js';

export const BASE_PACKAGES = ['ggplot2', 'dplyr', 'tidyr'];

export function projectScript(project, { helpers, schemaOf, includeHelpers = true, date = new Date(), mixedEngine = 'lme4' }) {
  const order = topoOrder(project);
  const opts = { mixedEngine };
  const pkgs = [...new Set([...BASE_PACKAGES, ...order.flatMap((it) => itemPackages(it, opts))])];
  const out = [];
  out.push(`# ${project.name}`);
  out.push(`# R script generated by Agrafeuse on ${date.toISOString().slice(0, 10)}.`);
  out.push('# It recreates every data table, analysis and graph in the project.');
  out.push('#');
  out.push(`# If ${ABOUT.name} contributed to your work, please cite: ${CITATION}`);
  out.push('# Please also cite R and the R packages used: citation(); citation("ggplot2"); etc.');
  out.push(`# Packages needed: install.packages(c(${pkgs.map((p) => `"${p}"`).join(', ')}))`);
  out.push('');
  for (const p of BASE_PACKAGES) out.push(`library(${p})`);
  out.push('');
  if (includeHelpers) {
    out.push('# ---- Agrafeuse helper functions ------------------------------------------');
    out.push(helpers.trim());
  } else {
    out.push('source("agrafeuse-helpers.R")  # helper functions (ag_*) from Agrafeuse');
  }
  const sections = { data: 'Data', transform: 'Transforms', analysis: 'Analyses', graph: 'Graphs' };
  let last = null;
  for (const it of order) {
    if (it.kind !== last) {
      out.push('');
      out.push(`# ---- ${sections[it.kind]} ${'-'.repeat(Math.max(4, 70 - sections[it.kind].length))}`);
      last = it.kind;
    }
    out.push('');
    out.push(`# ${it.name}`);
    try {
      out.push(itemCode(project, it, schemaOf, opts));
      if (it.kind === 'analysis') out.push(`print(${it.rname})`);
      if (it.kind === 'graph') {
        out.push(`print(${it.rname})`);
        const s = it.size || {};
        out.push(`# ggsave("${it.rname}.pdf", ${it.rname}, width = ${s.width || 5}, height = ${s.height || 4})`);
      }
    } catch (e) {
      out.push(`# (not included: ${e.message})`);
    }
  }
  return out.join('\n') + '\n';
}
